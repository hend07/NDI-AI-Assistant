def access_check(asset_id, role):
    meta = CATALOG.get(asset_id)

    if not meta:
        return {
            "allowed": False,
            "reason": "Asset is not registered."
        }

    return {
        "allowed": role in meta.allowed_roles,
        "classification": meta.classification,
        "owner": meta.owner,
        "reason": "Allowed" if role in meta.allowed_roles else "Role denied"
    }


class DataQuality:

    required = [
        "event_id",
        "event_time",
        "asset_id",
        "value",
        "source"
    ]

    def run(self, df):

        missing = [
            c for c in self.required
            if c not in df.columns
        ]

        schema_ok = not missing

        if not schema_ok:
            return {
                "schema": {
                    "passed": False,
                    "missing_columns": missing
                },
                "overall_passed": False
            }

        completeness = (
            1 -
            df[self.required].isna().sum().sum()
            / (len(df) * len(self.required))
            if len(df) else 0
        )

        duplicates = int(
            df["event_id"].duplicated().sum()
        )

        times = pd.to_datetime(
            df["event_time"],
            errors="coerce",
            utc=True
        ).notna()

        values = pd.to_numeric(
            df["value"],
            errors="coerce"
        ).notna()

        sources = (
            df["source"]
            .astype(str)
            .str.len()
            .gt(0)
        )

        invalid = int(
            (~(times & values & sources)).sum()
        )

        result = {
            "schema": {
                "passed": True,
                "missing_columns": []
            },
            "completeness": {
                "passed": completeness >= .95,
                "score": round(float(completeness), 4)
            },
            "duplicates": {
                "passed": duplicates == 0,
                "count": duplicates
            },
            "validity": {
                "passed": invalid == 0,
                "invalid_count": invalid
            }
        }

        result["overall_passed"] = all(
            x["passed"] for x in result.values()
        )

        return result


def normalize_events(df):

    out = df.copy()

    out["event_time"] = pd.to_datetime(
        out["event_time"],
        errors="coerce",
        utc=True
    )

    out["value"] = pd.to_numeric(
        out["value"],
        errors="coerce"
    )

    out = out.dropna(
        subset=[
            "event_id",
            "event_time",
            "asset_id",
            "value",
            "source"
        ]
    )

    return out.drop_duplicates(
        "event_id",
        keep="last"
    )


