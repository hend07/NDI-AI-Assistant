def clean_text(t):
    return re.sub(r"\s+"," ",t or "").strip()

def chunks(t, size=900, overlap=150):
    words=t.split()
    step=max(1,size-overlap)
    return [" ".join(words[i:i+size]) for i in range(0,len(words),step) if words[i:i+size]]

def ingest_pdf(pdf_path, start_page=1, end_page=None):
    pdf=Path(pdf_path)
    if not pdf.exists():
        raise FileNotFoundError(f"PDF not found: {pdf}")
    reader=PdfReader(str(pdf))
    end_page=min(end_page or len(reader.pages), len(reader.pages))
    docs, ids, metas=[],[],[]
    for page in range(start_page,end_page+1):
        text=clean_text(reader.pages[page-1].extract_text())
        for n,ch in enumerate(chunks(text),1):
            hid=hashlib.sha256(f"{pdf.name}|{page}|{n}|{ch}".encode()).hexdigest()[:20]
            docs.append(f"دليل نضيء — الصفحة {page} — المقطع {n}\n{ch}")
            ids.append(f"NDI-{page}-{n}-{hid}")
            metas.append({"source":pdf.name,"page":page,"chunk":n,"asset_id":"NDI_KNOWLEDGE_BASE"})
    if not docs: raise ValueError("No extractable text found.")
    vectors=embedder.encode(docs, normalize_embeddings=True, show_progress_bar=True).tolist()
    collection.upsert(ids=ids,documents=docs,embeddings=vectors,metadatas=metas)
    return len(docs)

